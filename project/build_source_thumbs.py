"""
Cover thumbnails for the TEG Contactor Sizer's Sources panel: page 1 of each PDF, slide 1 of each deck.
Decks are exported from temporary copies (never the open master). Output: source_thumbs.js
(const SOURCE_THUMBS = {id: data URI}), loaded by the template and inlined by build_contactor_tool.py.

Run:  python build_source_thumbs.py
"""
import base64
import glob
import io
import json
import os
import shutil
import tempfile

import fitz
from PIL import Image

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
HERE = os.path.dirname(os.path.abspath(__file__))
CHEME = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(HERE, "source_thumbs.js")
WIDTH = 120                                   # px; JPEG quality below keeps each ~4-8 KB

PDFS = {
    "gpsa": "Design/Glycol Dehydrator/GPSA Engineering Data Book*.pdf",
    "perry9": "Textbooks (Level 1)/Handbooks & Quick Reference/Perry's 9th Edition.pdf",
    "perry8": "Textbooks (Level 1)/Handbooks & Quick Reference/Perrys_Chemical_Engineers_Handbook 8th Edition.pdf",
    "ludwig": "Textbooks (Level 1)/Process & Plant Design/Ludwig applied_process_design_volume2_3e (Towers).pdf",
    "rot": "Textbooks (Level 1)/Handbooks & Quick Reference/ChemE Rules of Thumb.pdf",
    "encyc": "Textbooks (Level 1)/the encyclopedia of chemical process*.pdf",
    "seider": "FEL Projects/Economics/Economics Textbook 1*.pdf",
    "peters": "FEL Projects/Economics/Economics Textbook 2*.pdf",
    "asme": "Cheme Tools/Equipment Selection and Sizing/Vessel Scale Up/Asme-Section-II*.pdf",
    "ogj": "Design/Glycol Dehydrator/Oil & Gas Journal*.pdf",
    "cabeq": "Design/Glycol Dehydrator/Triethylene Glycol Dehydration*.pdf",
}
DECKS = {
    "absorbers": "Plant Resources/Absorbers.pptx",
    "absheur": "Design/Absorber Heuristics.pptx",
    "eos": "Design/Equation of State Selection.pptx",
    "econdeck": "FEL Projects/Economics/Equipment Cost Estimations.pptx",
}


def jpeg_uri(img):
    img.thumbnail((WIDTH, WIDTH * 2))
    buf = io.BytesIO()
    img.convert("RGB").save(buf, "JPEG", quality=70)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


if __name__ == "__main__":
    thumbs = {}
    for key, pat in PDFS.items():
        path = glob.glob(os.path.join(CHEME, pat))[0]
        pix = fitz.open(path)[0].get_pixmap(dpi=40)
        thumbs[key] = jpeg_uri(Image.open(io.BytesIO(pix.tobytes("png"))))
    import win32com.client as w
    pp = w.Dispatch("PowerPoint.Application")
    tmp = tempfile.mkdtemp()
    for key, rel in DECKS.items():
        copy = os.path.join(tmp, key + ".pptx")
        shutil.copy(os.path.join(CHEME, rel), copy)
        pres = pp.Presentations.Open(copy, True, False, False)        # read-only, no window
        png = os.path.join(tmp, key + ".png")
        pres.Slides(1).Export(png, "PNG", 480, 270)
        pres.Close()                                                  # closes the temporary copy only
        thumbs[key] = jpeg_uri(Image.open(png))
    shutil.rmtree(tmp, ignore_errors=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by build_source_thumbs.py -- do not edit\nconst SOURCE_THUMBS = " + json.dumps(thumbs) + ";\n")
    print(f"wrote {OUT} ({os.path.getsize(OUT) / 1024:.0f} KB, {len(thumbs)} thumbnails)")
