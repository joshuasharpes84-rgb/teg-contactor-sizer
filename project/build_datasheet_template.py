"""
Absorber datasheet template for the TEG Contactor Sizer: Coulson & Richardson Vol 6, Appendix G, "Vessel data
sheet" (p.991) + "Column Tray data sheet" (p.992). No library source has a packed-tower or absorber-specific sheet
(searched 2026-10-27: Coulson, Rules of Thumb Appendix 8, Ludwig, Perry's, Seider), so packed internals go on the
vessel sheet. Output: datasheet_template.js (const DATASHEET_PDF_B64), inlined by build_contactor_tool.py.
Field positions in the page script were read from this PDF's text layer (label coordinates).

Run:  python build_datasheet_template.py
"""
import base64
import glob
import os

import fitz

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = glob.glob(r"C:\Users\Administrator\Downloads\ChemE\Textbooks (Level 1)\**\Chemical Engineering Design (Coulson*.pdf",
                recursive=True)[0]
PAGES = (1008, 1009)                      # PDF pages: vessel data sheet, column tray data sheet
OUT = os.path.join(HERE, "datasheet_template.js")

if __name__ == "__main__":
    src, doc = fitz.open(SRC), fitz.open()
    for p in PAGES:
        doc.insert_pdf(src, from_page=p - 1, to_page=p - 1)
    data = doc.tobytes(garbage=4, deflate=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by build_datasheet_template.py -- do not edit. Coulson & Richardson Vol 6 App G pp.991-992.\n")
        fh.write(f"const DATASHEET_PDF_B64 = \"{base64.b64encode(data).decode()}\";\n")
    print(f"wrote {OUT} ({len(data) / 1024:.0f} KB PDF, page size {doc[0].rect})")
