"""
Publishes the TEG Contactor Sizer to the portfolio site and its GitHub package (local files only; no deploy, no push).

The files in this folder stay the single source. This script:
  1. rebuilds the page (build_contactor_tool.py) and copies it to portfolio-site/tools/teg-contactor/index.html,
     adding the site's analytics beacon (/assets/track.js), as the other full-page tools do;
  2. copies README.md to the package builder's readmes/teg-contactor-sizer.md;
  3. splices a full-page tool section into portfolio-site index.html between the BEGIN/END TEG CONTACTOR comments
     (inserted after the Cleaning Interval section on first run).

SOURCES.md and DECISIONS.md reach the repo through build_packages.py's PROVENANCE map.
Then: create the GitHub repo -> build_packages.py -> push -> Chatbot/build_knowledge_bundle.py -> deploy.
"""
import os
import subprocess
import sys

# ===========================================================================
# Paths
# ===========================================================================
HERE = os.path.dirname(os.path.abspath(__file__))
BUILT = os.path.join(os.path.dirname(HERE), "TEG Contactor Sizer.html")
SITE = os.path.normpath(os.path.join(HERE, r"..\..\..\..\Interview Prep\portfolio-site"))
INDEX = os.path.join(SITE, "index.html")
DEST = os.path.join(SITE, "tools", "teg-contactor")
README_DEST = os.path.join(SITE, "Not on Website", "github_packages", "readmes", "teg-contactor-sizer.md")

REPO_URL = "https://github.com/joshuasharpes84-rgb/teg-contactor-sizer"
BEGIN = "<!-- BEGIN TEG CONTACTOR"
END = "<!-- END TEG CONTACTOR -->"
ANCHOR = "<!-- END CLEANING INTERVAL -->"
BEACON = '<script src="/assets/track.js" defer></script>'

GH_ICON = ('<svg width="13" height="13" viewBox="0 0 16 16" fill="currentColor" aria-hidden="true"><path d="M8 0C3.58 0 0 '
           '3.58 0 8c0 3.54 2.29 6.53 5.47 7.59.4.07.55-.17.55-.38 0-.19-.01-.82-.01-1.49-2.01.37-2.53-.49-2.69-.94-.09-.23-.48-'
           '.94-.82-1.13-.28-.15-.68-.52-.01-.53.63-.01 1.08.58 1.23.82.72 1.21 1.87.87 2.33.66.07-.52.28-.87.51-1.07-1.78-.2-3.64-'
           '.89-3.64-3.95 0-.87.31-1.59.82-2.15-.08-.2-.36-1.02.08-2.12 0 0 .67-.21 2.2.82.64-.18 1.32-.27 2-.27.68 0 1.36.09 2 '
           '.27 1.53-1.04 2.2-.82 2.2-.82.44 1.1.16 1.92.08 2.12.51.56.82 1.27.82 2.15 0 3.07-1.87 3.75-3.65 3.95.29.25.54.73.54 '
           '1.48 0 1.07-.01 1.93-.01 2.2 0 .21.15.46.55.38A8.013 8.013 0 0016 8c0-4.42-3.58-8-8-8z"/></svg>')

SECTION = f"""{BEGIN} (generated by ChemE\\Design\\Glycol Dehydrator\\Contactor Sizing\\publish_to_portfolio.py; edit the tool folder, not this) -->
    <!-- ── TEG Contactor Sizer ── -->
    <details>
      <summary>
        <span class="sum-arrow">›</span>
        <span class="sum-title">TEG Contactor Sizer — Glycol Gas Dehydration, Every Internals Type Compared</span>
        <a class="sum-gh" href="{REPO_URL}" target="_blank" rel="noopener" title="Method, sources and code - README written for engineers and their AI assistants" onclick="event.stopPropagation()">{GH_ICON}<span>Method &amp; code</span></a>
        <span class="sum-count">full page</span>
      </summary>
      <div class="details-body">
        <p class="card-desc">Set a dehydration case (gas rate, pressure, temperature, outlet water spec, glycol quality) and the tool sizes the TEG contactor three ways: structured packing, bubble-cap trays and random packing, from sourced methods (Perry's, Ludwig, Kister) run through my own selection workflow, with GPSA rules of thumb shown only as a check. It ranks all 117 tabulated packings at the case, flags when the recommended internals shift with the operating point, prices each option from shell thickness to lifecycle cost, and prints a filled vessel and tray datasheet. Key findings: at TEG liquid rates stainless random packing will not wet, structured packing has no published size-selection procedure, and the tray efficiency field data sit well below the textbook correlations.</p>
        <a class="card-link" href="tools/teg-contactor/" target="_blank" rel="noopener">Open Tool</a>
      </div>
    </details>
{END}"""


# ===========================================================================
# Steps
# ===========================================================================
def publish_page():
    subprocess.run([sys.executable, os.path.join(HERE, "build_contactor_tool.py")], check=True)
    page = open(BUILT, encoding="utf-8").read()
    if BEACON not in page:
        page = page.replace("</body>", BEACON + "\n</body>", 1) if "</body>" in page else page.rstrip() + "\n" + BEACON + "\n"
    os.makedirs(DEST, exist_ok=True)
    open(os.path.join(DEST, "index.html"), "w", encoding="utf-8", newline="\n").write(page)
    print(f"page -> {DEST} ({len(page) / 1024:.0f} KB)")


def publish_readme():
    text = open(os.path.join(HERE, "README.md"), encoding="utf-8").read()
    text = text.replace("| Runs | Open `index.html` in any browser, offline.",
                        "| Runs | Live at https://jsharpes-portfolio.netlify.app/tools/teg-contactor/, or open `index.html` in any browser, offline.", 1)
    os.makedirs(os.path.dirname(README_DEST), exist_ok=True)
    open(README_DEST, "w", encoding="utf-8", newline="\n").write(text)
    print(f"README -> {README_DEST}")


def publish_section():
    html = open(INDEX, encoding="utf-8").read()
    if BEGIN in html:
        a = html.index(BEGIN)
        b = html.index(END, a) + len(END)
        html = html[:a] + SECTION + html[b:]
        action = "replaced"
    else:
        assert html.count(ANCHOR) == 1, "Cleaning Interval end marker not found"
        i = html.index(ANCHOR) + len(ANCHOR)
        html = html[:i] + "\n\n    " + SECTION + html[i:]
        action = "inserted"
    open(INDEX, "w", encoding="utf-8", newline="\r\n").write(html.replace("\r\n", "\n"))   # index.html is CRLF
    print(f"{action} TEG Contactor section in {INDEX}")


if __name__ == "__main__":
    publish_page()
    publish_readme()
    publish_section()
