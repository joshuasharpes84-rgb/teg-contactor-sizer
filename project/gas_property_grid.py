"""
Dry-gas density grid for the TEG Contactor Sizer's P/T sliders.

Same route as the 2026-10-22 basis value (57.44 kg/m3, Z 0.8634 at 1000 psig / 100 F): EOS workflow
step 5 pick PC-SAFT (feos), illustrative dry-gas composition from eos_workflow_coverage_check.py
(SG 0.633). The browser cannot run feos, so the sizer interpolates this grid.

Run:  python gas_property_grid.py   -> gas_props_grid.js (loaded by the template, inlined by build_contactor_tool.py)
"""
import json
import os

import numpy as np
import feos
import si_units as si

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "gas_props_grid.js")
PARAM_ROOT = r"C:\Users\Administrator\Downloads\ChemE\Cheme Tools\Thermodynamic Properties\References\EOS Parameters"
PCSAFT_DIR = os.path.join(PARAM_ROOT, "feos", "pcsaft")
PCSAFT_FILES = ("esper2023.json", "eller2022.json")      # first file holding a CAS wins (eos_vle_models.py)

COMP = [("methane", "74-82-8", 0.88), ("ethane", "74-84-0", 0.06), ("propane", "74-98-6", 0.03),
        ("carbon dioxide", "124-38-9", 0.015), ("nitrogen", "7727-37-9", 0.015)]
P_PSIG = list(range(300, 1601, 50))      # covers the slider band with margin
T_F = list(range(50, 141, 5))
F_TO_K = lambda f: (f - 32) / 1.8 + 273.15
PSIG_TO_PA = lambda p: (p + 14.696) * 6894.757


def build_eos():
    where = {}
    for fn in PCSAFT_FILES:
        with open(os.path.join(PCSAFT_DIR, fn), encoding="utf-8") as fh:
            for rec in json.load(fh):
                where.setdefault(rec["identifier"].get("cas"), fn)
    by_file = {}
    for _, cas, _ in COMP:
        by_file.setdefault(where[cas], []).append(cas)
    inp = [(cs, os.path.join(PCSAFT_DIR, fn)) for fn, cs in by_file.items()]
    params = feos.Parameters.from_multiple_json(inp, identifier_option=feos.IdentifierOption.Cas)
    order = [r.identifier.cas for r in params.pure_records]
    z = np.array([dict((c, x) for _, c, x in COMP)[c] for c in order])
    mw = np.array([r.molarweight for r in params.pure_records])
    return feos.EquationOfState.pcsaft(params), z, float(z @ mw)


if __name__ == "__main__":
    eos, z, mw = build_eos()
    rho = []
    for tf in T_F:
        row = []
        for pg in P_PSIG:
            s = feos.State(eos, temperature=F_TO_K(tf) * si.KELVIN, pressure=PSIG_TO_PA(pg) * si.PASCAL,
                           composition=z, density_initialization="vapor")
            row.append(round(s.mass_density() / (si.KILOGRAM / si.METER ** 3), 3))
        rho.append(row)
    chk = rho[T_F.index(100)][P_PSIG.index(1000)]
    print(f"MW {mw:.3f}; rho at 1000 psig / 100 F = {chk:.2f} kg/m3 (basis 57.44)")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// Generated by gas_property_grid.py -- do not edit\nconst GAS_GRID = ")
        json.dump({"source": "PC-SAFT (feos), EOS workflow step 5 pick; dry gas SG 0.633 illustrative",
                   "MW": round(mw, 3), "P_psig": P_PSIG, "T_F": T_F, "rho": rho}, fh)
        fh.write(";\n")
    print(f"wrote {OUT}")
